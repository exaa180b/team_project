-- =========================================================
-- Catalog: artist, album, song, genre, song_genre
-- =========================================================

CREATE TABLE artist (
    artist_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_name  TEXT NOT NULL,
    country      TEXT                      -- nullable: most datasets have no country
);

CREATE TABLE album (
    album_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id     INTEGER NOT NULL REFERENCES artist (artist_id) ON DELETE RESTRICT,
    album_title   TEXT NOT NULL,
    release_date  DATE
);

CREATE TABLE song (
    song_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id      INTEGER NOT NULL REFERENCES album (album_id) ON DELETE RESTRICT,
    song_title    TEXT NOT NULL,
    duration_ms   INTEGER NOT NULL CHECK (duration_ms > 0),   -- datasets give milliseconds
    track_number  INTEGER CHECK (track_number > 0)
);

CREATE TABLE genre (
    genre_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name  TEXT NOT NULL UNIQUE
);

CREATE TABLE song_genre (
    song_id   INTEGER NOT NULL REFERENCES song (song_id)   ON DELETE CASCADE,
    genre_id  INTEGER NOT NULL REFERENCES genre (genre_id) ON DELETE CASCADE,
    PRIMARY KEY (song_id, genre_id)
);


-- =========================================================
-- Users and their activity
-- =========================================================

CREATE TABLE app_user (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       TEXT NOT NULL UNIQUE,
    email          TEXT NOT NULL UNIQUE,
    password_hash  TEXT NOT NULL,          -- store hashes only, never plain passwords
    date_joined    DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE liked_song (
    user_id   INTEGER NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    song_id   INTEGER NOT NULL REFERENCES song (song_id)     ON DELETE CASCADE,
    liked_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, song_id)
);

-- One row per play. This is the big table (target: 100k+ rows).
CREATE TABLE listening_history (
    history_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    song_id     INTEGER NOT NULL REFERENCES song (song_id)     ON DELETE RESTRICT,
    played_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- =========================================================
-- Playlists
-- =========================================================

CREATE TABLE playlist (
    playlist_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,  -- owner
    playlist_name  TEXT NOT NULL CHECK (length(trim(playlist_name)) > 0),
    description    TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- A song can appear in a playlist once (composite key), as in the ER diagram.
CREATE TABLE playlist_song (
    playlist_id  INTEGER NOT NULL REFERENCES playlist (playlist_id) ON DELETE CASCADE,
    song_id      INTEGER NOT NULL REFERENCES song (song_id)         ON DELETE CASCADE,
    added_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (playlist_id, song_id)
);

-- New: lets several users edit one playlist, so collaborative playlists
-- can be tested. The owner stays in playlist.user_id.
CREATE TABLE playlist_collaborator (
    playlist_id  INTEGER NOT NULL REFERENCES playlist (playlist_id) ON DELETE CASCADE,
    user_id      INTEGER NOT NULL REFERENCES app_user (user_id)     ON DELETE CASCADE,
    added_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (playlist_id, user_id)
);
